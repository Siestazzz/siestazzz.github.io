const fs=require('node:fs'),assert=require('node:assert/strict');
const base='public/game-assets/map/area7/';
const scene=JSON.parse(fs.readFileSync(base+'scene.json')),fx=JSON.parse(fs.readFileSync(base+'effects.json'));
assert.equal(scene.source,'area/area7');
assert.equal(scene.sha256,'4d889dd6781e78c19afb1221204219a11f4d065ca82c269dec3167985e27320d');
assert.deepEqual(scene.sprites.map(s=>s.file).sort(),['background.png','foreground.png','stage_light.png','stage_light2.png']);
assert.equal(fx.sources[0].sha256,scene.sha256);assert.equal(fx.groups.length,20);
assert.equal(fx.textures.length,5);
assert(fx.groups.every(g=>g.path.startsWith('area7/Background/')));
const lights=fx.groups.filter(g=>g.shaderId==='6140383380374060507');
assert.equal(lights.length,8);
assert(lights.every(g=>g.additive&&g.customBlend.mode===0&&g.customBlend.max===1));
const spot=fx.groups.find(g=>g.id==='7436878384713094626');
assert(spot.size3D);assert.equal(spot.size.max,2);assert.equal(spot.sizeY.max,4);
assert.deepEqual(spot.bursts.map(b=>b.time),[0,5]);assert.equal(spot.duration,10);
assert(fx.groups.filter(g=>g.mesh?.vertices.length===30).every(g=>g.cullBack));
for(const s of [...scene.sprites,...fx.textures])assert(fs.existsSync(base+s.file),s.file);
assert(fs.readFileSync('public/index.html','utf8').includes('scene-back-layers'));
const items=JSON.parse(fs.readFileSync(base+'items.json'));
assert.equal(items.sprites.length,9);
const clover=items.sprites.find(s=>s.source==='areaitem/areaitem0707');
assert.equal(clover.sha256,'e9172dfd24e35733c17450b2243139e2bbd71878ade1adbf4cbc130239c7c817');
assert.deepEqual(clover.position,[2041,-912]);assert.deepEqual(clover.size,[1601,913]);
assert.equal(clover.spawnTransform,'-8906712583894700021');
for(const s of items.sprites)assert(fs.existsSync(base+s.file));
console.log('PASS: stage bundle hash, four original layers, 20 emitters, custom additive channel, anisotropic lights and timed bursts.');
