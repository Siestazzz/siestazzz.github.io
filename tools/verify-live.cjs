const fs=require('node:fs'),assert=require('node:assert/strict');
const {parseHTML}=require('../pjskapk/analysis-tools/dom/node_modules/linkedom');
const {document}=parseHTML(fs.readFileSync('public/live/index.html','utf8'));
const cards=[...document.querySelectorAll('.live-menu-card')];
assert.equal(cards.length,2);
assert.equal(cards[0].getAttribute('href'),'/search/');
assert.equal(cards[0].querySelector('small').textContent,'READING');
assert.equal(cards[1].getAttribute('aria-disabled'),'true');
assert.equal(cards[1].getAttribute('href'),null);
assert.equal(cards[1].querySelector('small').textContent,'SOLO LIVE');
assert.equal(document.querySelector('.live-tile'),null);
for(const img of cards.flatMap(c=>[...c.querySelectorAll('img')]))assert(fs.existsSync('public'+img.getAttribute('src')));
assert.equal(document.querySelector('feColorMatrix'),null);
assert(document.querySelector('link[href="/css/live-menu.css"]'));
console.log('PASS: reference cards and local SVGs, reading route, inactive solo, no sprite filters or square tiles.');
